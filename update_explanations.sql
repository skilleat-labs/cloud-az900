## 1. 왜 ''예''인가?

**Azure Monitor**는 단일 구독뿐만 아니라 **여러 Azure 구독과 테넌트에 걸쳐 리소스를 통합 모니터링**할 수 있도록 설계되었습니다. 이를 위해 Azure Monitor는 **Log Analytics 워크스페이스**와 **Application Insights**를 통해 중앙 집중식 모니터링을 제공하며, 적절한 **RBAC(역할 기반 액세스 제어)** 권한이 있다면 여러 구독의 데이터를 한곳에서 수집하고 분석할 수 있습니다.

## 2. 학생들이 흔히 헷갈리는 포인트

- **구독 경계 인식 부족**: Azure 리소스는 구독 단위로 관리되지만, Monitor는 이 경계를 넘을 수 있다는 점을 간과합니다.
- **워크스페이스의 역할 혼동**: Log Analytics 워크스페이스가 각 구독마다 별도여야 한다고 생각하지만, 실제로는 한 워크스페이스가 여러 구독의 데이터를 수집할 수 있습니다.

## 3. 핵심 개념 한 줄 요약

**Azure Monitor는 RBAC 권한만 있으면 다중 구독 환경에서 중앙 집중식 모니터링을 지원합니다.**

